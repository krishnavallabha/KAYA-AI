# defines db tables for entire system
'''
Project: Contains basic project details.
Activity: Stores schedule tasks, critical path boolean, and baseline dates.
ActivityRelation: Tracks predecessor/successor dependencies for the NetworkX graph.
Material: The tracking state per-order (Status, location, dynamic forecast ETA, delay probability, confidence score).
Signal: Stores the raw incoming ingestion logs (e.g. OCR text, email body, manual inputs) reconciled to a material.
Alert: Fired notifications when critical paths are affected or signal conflicts occur.
Action: Draft communication templates or PO adjustments generated by GPT.
'''


from sqlalchemy.engine import default
from sqlalchemy import null
from datetime import datetime,UTC
from sqlalchemy import Column,Integer,String,Float,DateTime,Boolean,ForeignKey,Table 
from sqlalchemy.orm import relationship
from backend.database import Base 


class Project(Base):
    __tablename__ = "projects"
    id = Column(Integer,primary_key=True,index=True)
    name = Column(String,index=True)
    description = Column(String,nullable=True)
    created_at = Column(DateTime,default=datetime.now(UTC))
    activities = relationship(
        "Activity",
        back_populates="project",
        cascade="all, delete-orphan"
    )


class Activity(Base):
    __tablename__ = "activities"
    id = Column(Integer,primary_key=True,index=True)
    project_id = Column(Integer,ForeignKey("projects.id"))
    name = Column(String,index=True)
    scheduled_start = Column(DateTime)
    scheduled_end = Column(DateTime)
    actual_start = Column(DateTime,nullable=True)
    actual_end = Column(DateTime,nullable=True)
    is_critical_path = Column(Boolean,default=False)
    status = Column(String,default="NOT_STARTED") # NOT_STARTED, IN_PROGRESS, COMpLETED
    project = relationship(
        "Project",
        back_populates="activities"
    )
    materials = relationship(
        "Material",
        back_populates="activity"
    )  


class ActivityRelation(Base):
    __tablename__ = "activity_relations"
    id = Column(Integer,primary_key=True,index=True)
    project_id = Column(Integer,ForeignKey("projects.id"))
    predecessor_id = Column(Integer,ForeignKey("activities.id"))
    successor_id = Column(Integer,ForeignKey("activities.id"))
    relation_type = Column(String,default="FS") # FS=finish-to-start, FF=finish-to-finish, SS=start-to-start, SF=start-to-finish


class Material(Base):
    __tablename__ = "materials"
    id = Column(Integer,primary_key=True,index=True)
    activity_id = Column(Integer,ForeignKey("activities.id"),nullable=True)
    sku = Column(String,index=True)
    description = Column(String,nullable=True)
    quantity = Colum(Float,default=1.0)
    status = Column(String,default="ORDERED") # ORDERED, FABRICATING, SHIPPED, IN_TRANSIT, DELIVERED 
    current_location = Column(String,nullable=True)
    vendor_name = Column(String,nullable=True)
    promised_delivery_date = Column(DateTime)
    forecast_delivery_date = Column(DateTime)
    delay_probability = Column(Float,default=0.0) # 0.0 to 1.0 (0% to 100%)
    confidence_score = Column(Float,default=1.0)
    activity = relationship(
        "Activity",
        back_populates="materials"
    )
    signals = relationship(
        "Signal",
        back_populates="material",
        cascade="all, delete-orphan"
    )
    alerts = relationship(
        "Alert",
        back_populates="material",
        cascade="all, delete-orphan"
    )


class Signal(Base):
    __tablename__ = "signals"
    id = Column(Integer, primary_key=True, index=True)
    material_id = Column(Integer, ForeignKey("materials.id"))
    source = Column(String) # EMAIL, VISION, PORTAL, MANUAL
    raw_content = Column(String)
    parsed_status = Column(String, nullable=True)
    timestamp = Column(DateTime, default=datetime.now(UTC))
    confidence_weight = Column(Float, default=1.0)
    material = relationship(
        "Material", 
        back_populates="signals"
    )


class Alert(Base):
    __tablename__ = "alerts"
    id = Column(Integer, primary_key=True, index=True)
    project_id = Column(Integer, ForeignKey("projects.id"))
    material_id = Column(Integer, ForeignKey("materials.id"), nullable=True)
    message = Column(String)
    severity = Column(String, default="WARNING") # INFO, WARNING, CRITICAL
    is_resolved = Column(Boolean, default=False)
    created_at = Column(DateTime, default=datetime.now(UTC))
    material = relationship(
        "Material", 
        back_populates="alerts"
    )


class Action(Base):
    __tablename__ = "actions"
    id = Column(Integer, primary_key=True, index=True)
    alert_id = Column(Integer, ForeignKey("alerts.id"))
    action_type = Column(String) # EMAIL_VENDOR, RFQ_SUBSTITUTION, PO_AMENDMENT
    draft_content = Column(String)
    status = Column(String, default="DRAFT") # DRAFT, APPROVED, SENT
    created_at = Column(DateTime, default=datetime.now(UTC))